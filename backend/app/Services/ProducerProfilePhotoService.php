<?php

declare(strict_types=1);

namespace App\Services;

use App\Jobs\GenerateImageVariants;
use App\Models\Producer;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;

class ProducerProfilePhotoService
{
    private const STORAGE_PATH = 'avatars/producers';

    private const THUMBNAIL_PATH = 'avatars/producers/thumbnails';

    private const MEDIUM_PATH = 'avatars/producers/medium';

    private const GRID_PATH = 'avatars/producers/grid';

    private const LARGE_PATH = 'avatars/producers/large';

    /**
     * Upload a profile photo for a Producer. The request only stores the
     * original and the row; all variants (150/800/400/1600) are generated by
     * a queued job — accessors fall back to the original in the meantime.
     *
     * @return array{photo: string}
     */
    public function uploadProfilePhoto(Producer $producer, UploadedFile $photo): array
    {
        $this->deleteProfilePhoto($producer);

        $extension = $photo->getClientOriginalExtension() ?: 'jpg';
        $filename = Str::uuid()->toString().'.'.$extension;

        Storage::disk('public')->putFileAs(self::STORAGE_PATH, $photo, $filename);

        // Variant columns stay null until the job fills them
        $producer->update([
            'profile_photo' => $filename,
            'profile_photo_thumbnail' => null,
            'profile_photo_medium' => null,
            'profile_photo_grid' => null,
            'profile_photo_large' => null,
        ]);

        dispatch(GenerateImageVariants::forModel($producer));

        return [
            'photo' => $filename,
        ];
    }

    /**
     * Delete profile photo and all its variants for a Producer.
     */
    public function deleteProfilePhoto(Producer $producer): bool
    {
        $deleted = false;
        $disk = Storage::disk('public');

        if ($producer->profile_photo) {
            $path = self::STORAGE_PATH.'/'.$producer->profile_photo;
            if ($disk->exists($path)) {
                $disk->delete($path);
                $deleted = true;
            }
        }

        if ($producer->profile_photo_thumbnail) {
            $path = self::THUMBNAIL_PATH.'/'.$producer->profile_photo_thumbnail;
            if ($disk->exists($path)) {
                $disk->delete($path);
                $deleted = true;
            }
        }

        if ($producer->profile_photo_medium) {
            $path = self::MEDIUM_PATH.'/'.$producer->profile_photo_medium;
            if ($disk->exists($path)) {
                $disk->delete($path);
                $deleted = true;
            }
        }

        if ($producer->profile_photo_grid) {
            $path = self::GRID_PATH.'/'.$producer->profile_photo_grid;
            if ($disk->exists($path)) {
                $disk->delete($path);
                $deleted = true;
            }
        }

        if ($producer->profile_photo_large) {
            $path = self::LARGE_PATH.'/'.$producer->profile_photo_large;
            if ($disk->exists($path)) {
                $disk->delete($path);
                $deleted = true;
            }
        }

        if ($producer->profile_photo
            || $producer->profile_photo_thumbnail
            || $producer->profile_photo_medium
            || $producer->profile_photo_grid
            || $producer->profile_photo_large) {
            $producer->update([
                'profile_photo' => null,
                'profile_photo_thumbnail' => null,
                'profile_photo_medium' => null,
                'profile_photo_grid' => null,
                'profile_photo_large' => null,
            ]);
        }

        return $deleted;
    }
}
